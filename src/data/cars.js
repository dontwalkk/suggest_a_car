// Only images whose license allows free reuse on a website are accepted:
//   - CC0 / Public Domain      -> no credit needed
//   - CC BY / CC BY-SA         -> free to use, but you must show a credit line
// NC (non-commercial) and ND (no-derivatives) licenses are always rejected.
// Set STRICT_PUBLIC_DOMAIN = true to accept ONLY CC0 / Public Domain (no credit
// needed, but far fewer car photos exist, so more cars will use the placeholder).

const STRICT_PUBLIC_DOMAIN = false;

const OK_LICENSE = STRICT_PUBLIC_DOMAIN
  ? /^(CC0|Public domain|PDM)/i
  : /^(CC0|Public domain|PDM|CC BY( |$)|CC BY-SA( |$))/i;

const CACHE_KEY = "carImageCache.v3";
const memory = {};

const readCache = () => { try { return JSON.parse(localStorage.getItem(CACHE_KEY) || "{}"); } catch { return {}; } };
const writeCache = (c) => { try { localStorage.setItem(CACHE_KEY, JSON.stringify(c)); } catch { /* ignore */ } };
const stripHtml = (h = "") => h.replace(/<[^>]*>/g, "").replace(/\s+/g, " ").trim();

export const getCarFallbackSvg = (brand = "", name = "") => {
  const title = (name || brand || "Car").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").slice(0, 20);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120" width="100%" height="100%"><defs><linearGradient id="bgGrad" x1="0%" y1="0%" x2="100%" y2="100%"><stop offset="0%" stop-color="#312e81" /><stop offset="100%" stop-color="#1e1b4b" /></linearGradient></defs><rect width="120" height="120" rx="12" fill="url(#bgGrad)" /><circle cx="60" cy="50" r="28" fill="rgba(99,102,241,0.25)" /><text x="60" y="58" font-size="28" text-anchor="middle" dominant-baseline="middle">🚗</text><text x="60" y="96" font-family="-apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif" font-weight="700" font-size="10" fill="#c7d2fe" text-anchor="middle">${title}</text></svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
};

export const placeholderImage = (car) => getCarFallbackSvg(car?.brand, car?.name);

// Returns { src, credit, license, sourceUrl }.  `credit` is "" when none is required.
export async function resolveCarImage(car) {
  const fallback = { src: car.imageUrl || car.image || placeholderImage(car), credit: "", license: "", sourceUrl: "" };
  if (car.imageUrl) return { ...fallback, src: car.imageUrl, credit: car.imageCredit || "" };
  if (memory[car.id]) return memory[car.id];
  const cache = readCache();
  if (cache[car.id]) return (memory[car.id] = cache[car.id]);

  const query = car.imageQuery || `${car.name.replace(/ (Hybrid|Pure|350h|GT|1500)$/i, "")} car`;
  const url =
    "https://commons.wikimedia.org/w/api.php?action=query&format=json&origin=*" +
    "&generator=search&gsrnamespace=6&gsrlimit=20" +
    `&gsrsearch=${encodeURIComponent(query + " filetype:bitmap")}` +
    "&prop=imageinfo&iiprop=url|size|mime|extmetadata&iiurlwidth=800";

  try {
    const res = await fetch(url);
    const data = await res.json();
    const candidates = Object.values(data?.query?.pages || {})
      .map((p) => p.imageinfo?.[0])
      .filter((i) => i && i.mime === "image/jpeg" && i.width > i.height && i.width >= 800)
      .map((i) => {
        const m = i.extmetadata || {};
        return {
          width: i.width,
          src: i.thumburl,
          license: m.LicenseShortName?.value || "",
          artist: stripHtml(m.Artist?.value),
          sourceUrl: i.descriptionurl,
        };
      })
      .filter((c) => c.src && OK_LICENSE.test(c.license))
      .sort((a, b) => b.width - a.width);

    const best = candidates[0];
    if (best) {
      const isPD = /^(CC0|Public domain|PDM)/i.test(best.license);
      const result = {
        src: best.src,
        license: best.license,
        sourceUrl: best.sourceUrl,
        credit: isPD ? "" : `Photo: ${best.artist || "Wikimedia Commons contributor"} / ${best.license}`,
      };
      memory[car.id] = result;
      writeCache({ ...readCache(), [car.id]: result });
      return result;
    }
  } catch { /* fall through to placeholder */ }
  return fallback;
}

